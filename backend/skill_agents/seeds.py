def seed_default_skills(session: Session) -> None:
    for definition in DEFAULT_SKILLS:
        existing = session.scalar(select(Skill).where(Skill.name == definition["name"]))
        if existing:
            continue
        session.add(
            Skill(
                **definition,
            )
        )
    session.commit()
